#!/usr/bin/env python3
"""Embed mainOS's 1x arrow for recovery and trusted overlays."""

from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parent.parent


def load_arrow():
    data = (ROOT / "tools/UI/Cursors/mainos-arrow.cur").read_bytes()
    reserved, kind, count = struct.unpack_from("<HHH", data)
    assert (reserved, kind) == (0, 2)
    for index in range(count):
        width, height, _, _, hx, hy, size, offset = struct.unpack_from("<BBBBHHII", data, 6 + index * 16)
        if (width, height) != (32, 32):
            continue
        dib, w, h, planes, bits, compression = struct.unpack_from("<IiiHHI", data, offset)
        assert (dib, w, h, planes, bits, compression) == (40, 32, 64, 1, 32, 0)
        assert size >= 40 + width * height * 4
        pixels = [
            struct.unpack_from("<I", data, offset + dib + ((height - 1 - y) * width + x) * 4)[0]
            for y in range(height)
            for x in range(width)
        ]
        return width, height, hx, hy, pixels
    raise ValueError("MainOS arrow has no 32x32 variant")


def main():
    width, height, hx, hy, pixels = load_arrow()
    rows = [
        "\t" + ", ".join(f"0x{pixel:08X}U" for pixel in pixels[start : start + 8]) + ","
        for start in range(0, len(pixels), 8)
    ]
    header = """#ifndef NXU_POINTER_CURSOR_H
#define NXU_POINTER_CURSOR_H

#include <stdint.h>

/* Generated by tools/generate_pointer_cursor.py from tools/UI/Cursors/mainos-arrow.cur.
 * This is mainOS's 1x arrow, including straight-alpha edges and shadow. */
"""
    header += f"#define NXU_POINTER_CURSOR_WIDTH {width}U\n#define NXU_POINTER_CURSOR_HEIGHT {height}U\n"
    header += f"#define NXU_POINTER_CURSOR_HOTSPOT_X {hx}U\n#define NXU_POINTER_CURSOR_HOTSPOT_Y {hy}U\n\n"
    header += (
        "static const uint32_t nxu_pointer_cursor_pixels[NXU_POINTER_CURSOR_WIDTH * NXU_POINTER_CURSOR_HEIGHT] = {\n"
        + "\n".join(rows)
        + "\n};\n"
    )
    header += """
/* Match WindowServer's straight-alpha ARGB8888 compositing. */
static inline uint32_t nxu_pointer_cursor_blend(uint32_t background, uint32_t source)
{
    uint32_t alpha = source >> 24;
    if (alpha == 0U) return background;
    uint32_t inverse = 255U - alpha;
    uint32_t result = 0xFF000000U;
    for (uint32_t shift = 0U; shift < 24U; shift += 8U) {
        uint32_t channel = (((source >> shift) & 255U) * alpha +
            ((background >> shift) & 255U) * inverse + 127U) / 255U;
        result |= channel << shift;
    }
    return result;
}

#endif
"""
    (ROOT / "frameworks/include/nxu/pointer_cursor.h").write_text(header)


if __name__ == "__main__":
    main()
