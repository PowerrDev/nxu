#!/usr/bin/env python3
"""Bake SF Mono Regular into a C grayscale glyph atlas for the Terminal app.

The Terminal is a C program with no runtime font rasteriser; it previously used
the fixed 8x16 console bitmap font. This tool rasterises SFMono-Regular.otf once
at build time (printable ASCII, 32..126) into an antialiased coverage atlas plus
per-glyph metrics, mirroring tools/generate_recovery_fonts.py. Rendered at 13 px
SF Mono advances exactly 8 px, so the Terminal keeps its 8x16 cell grid.

    python3 tools/generate_terminal_font.py <output.h>
"""

from __future__ import annotations

import sys
from pathlib import Path

from generate_recovery_fonts import emit_bytes, raster_face

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "tools/DiskRoot/System/Library/Fonts/Mono/SFMono-Regular.otf"
# 13 px: advance 8 (matches the Terminal's 8 px cell), ascent 13.
SIZE = 13


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: generate_terminal_font.py <output.h>")
    output = Path(sys.argv[1])

    pixels, glyphs, line_height = raster_face(FONT, SIZE)
    # SF Mono is monospaced: every printable glyph shares one advance.
    advance = glyphs[ord("M") - 32][5]

    lines = [
        "/* Generated by tools/generate_terminal_font.py from SFMono-Regular.otf. */",
        "/* Do not edit. */",
        "#ifndef NXU_TERMINAL_FONT_H",
        "#define NXU_TERMINAL_FONT_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "\tuint32_t offset;   /* start in g_terminal_font_pixels */",
        "\tuint8_t width;",
        "\tuint8_t height;",
        "\tint8_t x_offset;   /* left bearing from the pen */",
        "\tint8_t y_offset;   /* top from the line top (ascent + bbox top) */",
        "\tuint8_t advance;",
        "} terminal_font_glyph_t;",
        "",
        "#define TERMINAL_FONT_FIRST 32U",
        "#define TERMINAL_FONT_LAST 126U",
        f"#define TERMINAL_FONT_ADVANCE {advance}U",
        f"#define TERMINAL_FONT_LINE_HEIGHT {line_height}U",
        "",
        emit_bytes("g_terminal_font_pixels", pixels),
        "",
        "static const terminal_font_glyph_t g_terminal_font_glyphs[95] = {",
    ]
    for offset, width, height, x_offset, y_offset, adv in glyphs:
        lines.append(f"\t{{ {offset}U, {width}U, {height}U, {x_offset}, {y_offset}, {adv}U }},")
    lines += ["};", "", "#endif", ""]

    output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
